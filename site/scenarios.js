export function scenario(name) {
  if (!Object.hasOwn(SCENARIOS, name)) throw new Error("Unknown scenario");
  const clean = Array.from({ length: 12 }, (_, i) =>
    tx(
      `DAY-${String(i + 1).padStart(3, "0")}`,
      `CUSTOMER-${i + 1}`,
      `SHOP-${(i % 4) + 1}`,
      32.5 + i * 87.25,
      i * 32,
      { expected_fraud: false },
    ),
  );
  const mule = [
    ...["A", "B", "C"].map((u, i) =>
      tx(`MULE-${i + 1}`, `ACCOUNT-${u}`, "COLLECTOR", 650 + i * 200, i * 2, {
        device_id: "DEVICE-REUSED",
      }),
    ),
    tx("MULE-4", "COLLECTOR", "TRANSIT", 2400, 8),
    tx("MULE-5", "TRANSIT", "CASHOUT", 2380, 10),
    tx("MULE-6", "CASHOUT", "COLLECTOR", 2350, 12),
  ];
  const velocity = [450, 2100, 2300, 16500, 1200, 2450].map((amount, i) =>
    tx(`FAST-${i + 1}`, "WALLET-NOVA", `BENEFICIARY-${i + 1}`, amount, i * 2, {
      payment_method: "flouci",
      governorate: ["Tunis", "Sfax", "Sousse"][i % 3],
    }),
  );
  const structuring = [1410, 1435, 1470, 1460, 1425].map((amount, i) =>
    tx(`SPLIT-${i + 1}`, "WALLET-DELTA", "COLLECTOR-DELTA", amount, i * 4, {
      payment_method: "flouci",
    }),
  );
  const scams = [
    tx("REPORT-1", "CUSTOMER-S1", "UNVERIFIED-SELLER", 650, 5),
    tx("REPORT-2", "CUSTOMER-S2", "UNVERIFIED-SELLER", 820, 7),
    tx("REPORT-3", "CUSTOMER-S3", "UNVERIFIED-SELLER", 970, 9, {
      reported_scam: true,
    }),
  ];
  return name === "mixed"
    ? [...clean, ...mule, ...velocity, ...structuring, ...scams]
    : { clean, mule, velocity, structuring, scams }[name];
}
